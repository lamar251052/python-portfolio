# Question: what does print() put between values, and at the end of each line?
#
# My answer:
# 1. Between values, print() puts a space.
#    Example: print("lamar", "bilal") shows: lamar  bilal
# 2. At the end of each line, print() goes to a new line.
#
# Source: https://docs.python.org/3/library/functions.html#print

# Three values. Look: print() puts a space between them.
print("lamar ", "bilal ")